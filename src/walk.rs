//! Source discovery: honours .gitignore (even outside a git checkout) and
//! skips dependency, build and generated output that would otherwise
//! dominate any duplication report.

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use ignore::overrides::{Override, OverrideBuilder};
use ignore::{WalkBuilder, WalkState};

use crate::lang::{LANGS, lang_index_for_path};

const EXCLUDED_DIRS: &[&str] = &[
    "node_modules",
    "target",
    "dist",
    "build",
    "out",
    "bin",
    "obj",
    "vendor",
    "coverage",
    ".git",
    ".next",
    ".nuxt",
    ".svelte-kit",
    "__pycache__",
    ".venv",
    "venv",
    "Pods",
    ".gradle",
    "DerivedData",
    ".idea",
    ".vs",
];

const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "<auto-generated",
    "Code generated",
    "DO NOT EDIT",
    "autogenerated",
];

pub const MAX_FILE_BYTES: u64 = 1 << 20;

pub fn discover(
    root: &Path,
    exclude: &[String],
    languages: &[usize],
) -> anyhow::Result<Vec<(PathBuf, usize)>> {
    // A file named directly is scanned even in an opt-in language.
    let named = root.is_file() && languages.is_empty();
    let own: Vec<usize> = lang_index_for_path(root).into_iter().collect();
    let languages = if named { &own[..] } else { languages };
    let walker = WalkBuilder::new(root)
        .require_git(false)
        .overrides(exclude_overrides(root, exclude)?)
        .filter_entry(|e| {
            !e.file_type().is_some_and(|t| t.is_dir()) || !is_excluded_dir(e.file_name())
        })
        .build_parallel();
    let found = Mutex::new(Vec::new());
    walker.run(|| {
        Box::new(|entry| {
            if let Some(hit) = entry.ok().and_then(|e| accept(e.path(), languages)) {
                found.lock().unwrap().push(hit);
            }
            WalkState::Continue
        })
    });
    let mut files = found.into_inner().unwrap();
    files.sort();
    Ok(files)
}

pub fn exclude_overrides(root: &Path, exclude: &[String]) -> anyhow::Result<Override> {
    let mut overrides = OverrideBuilder::new(root);
    for glob in exclude {
        overrides.add(&format!("!{glob}"))?;
    }
    Ok(overrides.build()?)
}

/// The language of a file known from a listing rather than a walk (a git
/// revision), or `None` when a walk would have skipped it: an excluded or
/// hidden directory, or an `--exclude` matching it or any parent. `rel` is
/// relative to the scanned root.
pub fn accept_listed(rel: &Path, overrides: &Override, languages: &[usize]) -> Option<usize> {
    let skipped_name = rel.components().any(|c| {
        let name = c.as_os_str();
        is_excluded_dir(name) || name.to_str().is_some_and(|n| n.starts_with('.'))
    });
    let excluded = rel
        .ancestors()
        .filter(|a| !a.as_os_str().is_empty())
        .any(|a| overrides.matched(a, a != rel).is_ignore());
    if skipped_name || excluded {
        return None;
    }
    accept(rel, languages).map(|(_, lang)| lang)
}

fn is_excluded_dir(name: &std::ffi::OsStr) -> bool {
    name.to_str().is_some_and(|n| EXCLUDED_DIRS.contains(&n))
}

fn accept(path: &Path, languages: &[usize]) -> Option<(PathBuf, usize)> {
    let name = path.file_name()?.to_str()?.to_ascii_lowercase();
    if name.contains(".min.")
        || name.ends_with(".d.ts")
        || name.contains(".designer.")
        || name.contains(".g.")
    {
        return None;
    }
    let lang = lang_index_for_path(path)?;
    let wanted = if languages.is_empty() {
        !LANGS[lang].opt_in
    } else {
        languages.contains(&lang)
    };
    wanted.then(|| (path.to_path_buf(), lang))
}

/// Minified bundles and generated files are duplication nobody should
/// refactor by hand.
pub fn looks_generated(source: &str) -> bool {
    let head = &source[..source.floor_char_boundary(1024)];
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return true;
    }
    let lines = source.lines().count().max(1);
    source.len() > 4096 && source.len() / lines > 300
}
