// Where code generators write their output, often with no "generated"
// header for `looks_generated` to find. Full names only: `gen` frequently
// holds the hand-written generator itself.
const GENERATED_DIRS: &[&str] = &[
    "generated",
    "generated-src",
    "generated_src",
    "generated-sources",
    "__generated__",
];

const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "<auto-generated",
    "Code generated",
    "DO NOT EDIT",
    "autogenerated",
];

pub const MAX_FILE_BYTES: u64 = 1 << 20;

/// The most a file can be on disk and still fit `MAX_FILE_BYTES` once
/// normalised: UTF-16 to UTF-8 at most halves it, and CRLF to LF again.
/// Larger is rejected unread.
pub const MAX_RAW_BYTES: u64 = 4 * MAX_FILE_BYTES;

/// Source bytes as a scan reads them, or `None` when they are binary or too
/// large. The cap applies after normalising because raw size depends on the
/// checkout: an LF blob and its CRLF working copy must be judged alike.
pub fn scannable_text(bytes: Vec<u8>) -> Option<String> {
    let text = match String::from_utf8(bytes) {
        Ok(text) => text,
        Err(not_utf8) => decode_other(not_utf8.as_bytes())?,
    };
    let text = normalize_line_endings(text);
    (text.len() as u64 <= MAX_FILE_BYTES).then_some(text)
}

/// Bytes that are not UTF-8: UTF-16 when a BOM says so, otherwise some legacy
/// encoding, whose non-ASCII bytes matter too little to guess at. Code and
/// line ends are ASCII in all of those, so structure and line numbers survive
/// the replacement characters. A NUL then means binary, which is also what
/// UTF-16 without a BOM reads as.
fn decode_other(bytes: &[u8]) -> Option<String> {
    let text = match bytes {
        [0xFF, 0xFE, rest @ ..] => decode_utf16(rest, u16::from_le_bytes),
        [0xFE, 0xFF, rest @ ..] => decode_utf16(rest, u16::from_be_bytes),
        _ => String::from_utf8_lossy(bytes).into_owned(),
    };
    (!text.contains('\0')).then_some(text)
}

fn decode_utf16(bytes: &[u8], unit: fn([u8; 2]) -> u16) -> String {
    let units = bytes.as_chunks().0.iter().map(|&pair| unit(pair));
    char::decode_utf16(units)
        .map(|c| c.unwrap_or(char::REPLACEMENT_CHARACTER))
        .collect()
}

/// A source file a walk turned up.
pub struct Found {
    pub path: PathBuf,
    pub lang: usize,
    /// A config's `include` names it, so a generated marker does not count.
    pub included: bool,
}

pub fn discover(
    root: &Path,
    filter: &PathFilter,
    languages: &[usize],
) -> anyhow::Result<Vec<Found>> {
    // A file named directly is scanned even in an opt-in language.
    let named = root.is_file() && languages.is_empty();
    let own: Vec<usize> = lang_index_for_path(root).into_iter().collect();
    let languages = if named { &own[..] } else { languages };
    let (start, entry_filter) = (root.to_path_buf(), filter.clone());
    let walker = WalkBuilder::new(root)
        .require_git(false)
        .hidden(false)
        .overrides(filter.overrides.clone())
        .filter_entry(move |e| {
            let rel = e.path().strip_prefix(&start).unwrap_or(e.path());
            match e.file_type().is_some_and(|t| t.is_dir()) {
                true => !entry_filter.skips_dir(rel),
                false => !entry_filter.skips_file(rel),
            }
        })
        .build_parallel();
    let found = Mutex::new(Vec::new());
    walker.run(|| {
        Box::new(|entry| {
            let regular = entry.ok().filter(is_regular_file);
            let hit = regular.and_then(|e| found_at(e.path(), root, filter, languages));
            if let Some(hit) = hit {
                found.lock().unwrap().push(hit);
            }
            WalkState::Continue
        })
    });
    if let Some(e) = filter.take_error() {
        return Err(e);
    }
    let mut files = found.into_inner().unwrap();
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

/// Symlinks stay out as they do on the revision side, or a tracked link
/// would read as new on every check. The path typed on the command line is
/// the exception: naming a link asks for what it points at.
fn is_regular_file(entry: &DirEntry) -> bool {
    match entry.depth() {
        0 => entry.path().is_file(),
        _ => entry.file_type().is_some_and(|t| t.is_file()),
    }
}

fn found_at(path: &Path, root: &Path, filter: &PathFilter, languages: &[usize]) -> Option<Found> {
    let (path, lang) = accept(path, languages)?;
    let rel = path.strip_prefix(root).unwrap_or(&path);
    // The revision side has no name for such a path, so a clone in one
    // would read as new on every check.
    rel.to_str()?;
    let included = filter.includes(rel);
    Some(Found {
        path,
        lang,
        included,
    })
}

/// The language of a file known from a listing rather than a walk (a git
/// revision), or `None` when a walk would have skipped it: a built-in
/// skipped directory, or an exclude matching it or any parent. `rel` is
/// relative to the scanned root.
pub fn accept_listed(rel: &Path, filter: &PathFilter, languages: &[usize]) -> Option<usize> {
    let excluded = rel
        .ancestors()
        .filter(|a| !a.as_os_str().is_empty())
        .any(|a| filter.excluded_by_glob(a, a != rel));
    // Every directory on the way, as the walk would prune it: a file under
    // an excluded directory stays out even where a pattern re-includes it.
    let pruned = rel
        .ancestors()
        .skip(1)
        .filter(|a| !a.as_os_str().is_empty())
        .any(|a| filter.skips_dir(a));
    if excluded || pruned || filter.skips_file(rel) {
        return None;
    }
    accept(rel, languages).map(|(_, lang)| lang)
}

/// File names never scanned: minified bundles, declaration files and
/// designer or generator output. `*.x.*` matches anywhere in the name,
/// `*.x` at its end.
const SKIPPED_NAMES: &[&str] = &["*.min.*", "*.d.ts", "*.designer.*", "*.g.*"];

fn is_skipped_name(name: &str) -> bool {
    SKIPPED_NAMES.iter().any(|glob| {
        let glob = &glob[1..];
        match glob.strip_suffix('*') {
            Some(inner) => name.contains(inner),
            None => name.ends_with(glob),
        }
    })
}

/// The skip list a config cannot see, for `doppelscan config` to show.
pub struct BuiltInSkips {
    pub dirs: &'static [&'static str],
    pub generated_dirs: &'static [&'static str],
    /// File name globs.
    pub names: &'static [&'static str],
    /// A file with one of these in its first KB is taken for generated.
    pub generated_markers: &'static [&'static str],
}

pub const BUILT_IN_SKIPS: BuiltInSkips = BuiltInSkips {
    dirs: EXCLUDED_DIRS,
    generated_dirs: GENERATED_DIRS,
    names: SKIPPED_NAMES,
    generated_markers: GENERATED_MARKERS,
};

pub(crate) fn is_excluded_dir(name: &std::ffi::OsStr) -> bool {
    name.to_str()
        .is_some_and(|n| EXCLUDED_DIRS.contains(&n) || GENERATED_DIRS.contains(&n))
}

fn accept(path: &Path, languages: &[usize]) -> Option<(PathBuf, usize)> {
    let name = path.file_name()?.to_str()?.to_ascii_lowercase();
    if is_skipped_name(&name) {
        return None;
    }
    let lang = lang_index_for_path(path)?;
    let wanted = if languages.is_empty() {
        !LANGS[lang].opt_in
    } else {
        languages.contains(&lang)
    };
    wanted.then(|| (path.to_path_buf(), lang))
}

/// Minified bundles and generated files are duplication nobody should
/// refactor by hand. An `included` file was asked for, marker or not; being
/// minified still rules it out, since nothing in it could be extracted.
/// Callers pass normalised text: CRs would push a marker out of the head and
/// count towards line length, so an LF revision and its CRLF checkout could
/// be judged differently.
pub fn looks_generated(source: &str, included: bool) -> bool {
    let head = &source[..source.floor_char_boundary(1024)];
    if !included && GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return true;
    }
    let lines = source.lines().count().max(1);
    source.len() > 4096 && source.len() / lines > 300
}
