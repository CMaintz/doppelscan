//! Source discovery: honours .gitignore (even outside a git checkout) and
//! skips dependency, build and generated output that would otherwise
//! dominate any duplication report.

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use ignore::overrides::OverrideBuilder;
use ignore::{WalkBuilder, WalkState};

use crate::lang::lang_index_for_path;

const EXCLUDED_DIRS: &[&str] = &[
    "node_modules",
    "target",
    "dist",
    "build",
    "out",
    "bin",
    "obj",
    "vendor",
    "coverage",
    ".git",
    ".next",
    ".nuxt",
    ".svelte-kit",
    "__pycache__",
    ".venv",
    "venv",
    "Pods",
    ".gradle",
    "DerivedData",
    ".idea",
    ".vs",
];

const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "<auto-generated",
    "Code generated",
    "DO NOT EDIT",
    "autogenerated",
];

pub const MAX_FILE_BYTES: u64 = 1 << 20;

pub fn discover(
    root: &Path,
    exclude: &[String],
    languages: &[usize],
) -> anyhow::Result<Vec<(PathBuf, usize)>> {
    let mut overrides = OverrideBuilder::new(root);
    for glob in exclude {
        overrides.add(&format!("!{glob}"))?;
    }
    let walker = WalkBuilder::new(root)
        .require_git(false)
        .overrides(overrides.build()?)
        .filter_entry(|e| {
            !e.file_type().is_some_and(|t| t.is_dir()) || !is_excluded_dir(e.file_name())
        })
        .build_parallel();
    let found = Mutex::new(Vec::new());
    walker.run(|| {
        Box::new(|entry| {
            if let Some(hit) = entry.ok().and_then(|e| accept(e.path(), languages)) {
                found.lock().unwrap().push(hit);
            }
            WalkState::Continue
        })
    });
    let mut files = found.into_inner().unwrap();
    files.sort();
    Ok(files)
}

fn is_excluded_dir(name: &std::ffi::OsStr) -> bool {
    name.to_str().is_some_and(|n| EXCLUDED_DIRS.contains(&n))
}

fn accept(path: &Path, languages: &[usize]) -> Option<(PathBuf, usize)> {
    let name = path.file_name()?.to_str()?.to_ascii_lowercase();
    if name.contains(".min.")
        || name.ends_with(".d.ts")
        || name.contains(".designer.")
        || name.contains(".g.")
    {
        return None;
    }
    let lang = lang_index_for_path(path)?;
    (languages.is_empty() || languages.contains(&lang)).then(|| (path.to_path_buf(), lang))
}

/// Minified bundles and generated files are duplication nobody should
/// refactor by hand.
pub fn looks_generated(source: &str) -> bool {
    let head = &source[..source.floor_char_boundary(1024)];
    if GENERATED_MARKERS.iter().any(|m| head.contains(m)) {
        return true;
    }
    let lines = source.lines().count().max(1);
    source.len() > 4096 && source.len() / lines > 300
}
