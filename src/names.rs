//! Readable names for clone groups, derived from the fingerprint when a
//! group is displayed. The fingerprint stays the identity: a name is never
//! stored, so baselines and `accept` entries do not depend on this list.
const WORD_BITS: u32 = 10;
const WORDS_PER_NAME: u32 = 4;
const FINGERPRINT_BITS: u32 = 48;
/// The name of the group with this 48-bit fingerprint. The top 40 bits pick
/// four words: two fingerprints that agree on them share a name, about
/// 0.0045 pairs expected among 100,000 groups (n(n-1)/2 / 2^40), where three
/// words (30 bits) would give 4.7. Same input, same name, across runs and
/// platforms.
pub fn name(fingerprint: u64) -> String {
    let word = |i| {
        let shift = FINGERPRINT_BITS - i * WORD_BITS;
        WORDS[(fingerprint >> shift) as usize & (WORDS.len() - 1)]
    };
    let words: Vec<&str> = (1..=WORDS_PER_NAME).map(word).collect();
    words.join("-")
}
